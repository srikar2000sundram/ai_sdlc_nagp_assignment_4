"""Check the AI interaction log and write a readable summary of it.

    python scripts/summarize_log.py            # write logs/ai-interactions-summary.md
    python scripts/summarize_log.py --check    # only validate the log; exit 1 when a line is wrong

The log (`logs/ai-interactions.jsonl`) is the machine-readable evidence. The summary is the same evidence for a human
reader: who did what with which tool and model, what the human decided, and which checks proved the result.
"""

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "logs" / "ai-interactions.jsonl"
SUMMARY = ROOT / "logs" / "ai-interactions-summary.md"

# The record shape, kept in step with FIELDS in .claude/hooks/log_event.py.
sys.path.insert(0, str(ROOT / ".claude" / "hooks"))
from log_event import FIELDS  # noqa: E402

LIST_FIELDS = ("related_ids", "skills_used", "subagents_used", "mcp_tools_used", "tools_used", "artifacts")


def read_log() -> list[dict]:
    """Every record in the log, in file order."""
    return [json.loads(line) for line in LOG.read_text(encoding="utf-8").splitlines() if line.strip()]


def problems(records: list[dict]) -> list[str]:
    """Everything wrong with the log: missing or extra keys, wrong types, repeated ids, links to unknown records."""
    found, seen = [], set()
    for number, record in enumerate(records, start=1):
        if tuple(record) != FIELDS:
            missing, extra = set(FIELDS) - set(record), set(record) - set(FIELDS)
            found.append(f"line {number}: keys differ from the schema (missing {sorted(missing)}, extra {sorted(extra)})")
            continue
        found += [f"line {number}: {name} must be a list" for name in LIST_FIELDS if not isinstance(record[name], list)]
        if record["id"] in seen:
            found.append(f"line {number}: id {record['id']} is used twice")
        seen.add(record["id"])
    for number, record in enumerate(records, start=1):
        found += [f"line {number}: related id {link} does not exist" for link in record.get("related_ids", []) if link not in seen]
    return found


def table(headers: tuple[str, ...], rows: list[tuple]) -> list[str]:
    """A Markdown table."""
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(str(cell).replace("|", "/") for cell in row) + " |" for row in rows]
    return lines + [""]


def count_table(title: str, counter: Counter, label: str) -> list[str]:
    """A titled two-column table of counts, largest first."""
    return [f"### {title}", ""] + table((label, "Records"), counter.most_common()) if counter else []


def capability_rows(records: list[dict], field: str, keys: tuple[str, ...]) -> list[tuple]:
    """Counted rows for a nested list field (skills, sub-agents, MCP tools): the chosen keys plus how often."""
    counter = Counter(tuple(item.get(key, "") for key in keys) for record in records for item in record[field])
    return [(*combination, times) for combination, times in counter.most_common()]


def summary_text(records: list[dict]) -> str:
    """The whole Markdown summary."""
    human_prompts = [r for r in records if r["event"] == "UserPromptSubmit" and r["agent_name"] != "harness"]
    decisions = [r for r in records if r["event"] == "HumanDecision"]
    checks = [r for r in records if r["event"] == "CheckSummary"]
    files = Counter(path for record in records for path in record["artifacts"])
    linked = Counter(r["parent_task"] for r in records if r["parent_task"])
    first, last = records[0]["timestamp"], records[-1]["timestamp"]

    out = [
        "# AI interaction log: readable summary", "",
        "Generated by `python scripts/summarize_log.py` from `logs/ai-interactions.jsonl`. Do not edit by hand.", "",
        f"- **Records:** {len(records)} (from {first} to {last})",
        "- **AI tool / model:** " + ", ".join(sorted({r["ai_tool"] + " / " + r["model"] for r in records})),
        f"- **Human prompts:** {len(human_prompts)}, **human decisions and corrections recorded:** {len(decisions)}",
        f"- **Checks run and summarized by the hook:** {len(checks)} ({sum(r['status'] == 'verified' for r in checks)} passed)",
        f"- **Files created or changed by the AI:** {len(files)}",
        "- **Written by:** " + ", ".join(f"{count} {source}" for source, count in Counter(r["source"] for r in records).most_common()),
        "",
        "## Who did the work", "",
    ]
    out += count_table("Agent type", Counter(r["agent_type"] for r in records), "Agent type")
    out += count_table("Agent name", Counter(r["agent_name"] for r in records), "Agent")
    out += count_table("Mode", Counter(r["mode"] for r in records), "Mode")
    out += count_table("Lifecycle stage", Counter(r["stage"] for r in records), "Stage")
    out += count_table("Outcome (status)", Counter(r["status"] for r in records), "Status")

    out += ["## Skills, sub-agents and tools", ""]
    skills = capability_rows(records, "skills_used", ("name", "type", "invocation"))
    out += ["### Skills used", ""] + (table(("Skill", "Type", "Invocation", "Times"), skills) if skills else ["None recorded.", ""])
    subagents = capability_rows(records, "subagents_used", ("name", "type", "status"))
    out += ["### Sub-agents used", ""] + (table(("Sub-agent", "Type", "Status", "Times"), subagents) if subagents else ["None recorded.", ""])
    mcp = capability_rows(records, "mcp_tools_used", ("server", "tool"))
    out += ["### MCP tools used", ""] + (table(("Server", "Tool", "Times"), mcp) if mcp else ["None recorded.", ""])
    tools = Counter(tool for record in records for tool in record["tools_used"])
    out += ["### Tools used", ""] + table(("Tool", "Calls"), tools.most_common(15))

    out += ["## Human oversight", "",
            "Decisions, corrections and limits the human set. Each links to the prompt it answered.", ""]
    out += table(("When", "Decision or correction", "Prompt it answers"),
                 [(r["timestamp"][:16].replace("T", " "), r["human_decision"], (r["request"] or "")[:70]) for r in decisions])

    out += ["## Verification evidence", "", "Every test, mutation or end-to-end run, as the hook summarized it.", ""]
    out += table(("When", "Check", "Status"), [(r["timestamp"][:16].replace("T", " "), r["action_verification"], r["status"]) for r in checks])

    out += ["## What each human prompt led to", ""]
    out += table(("When", "Prompt", "Records it led to"),
                 [(r["timestamp"][:16].replace("T", " "), r["request"][:80], linked.get(r["id"], 0)) for r in human_prompts])

    out += ["## Files the AI created or changed (most often first)", ""]
    out += table(("File", "Times"), files.most_common(20))

    out += [
        "## How to read the log honestly", "",
        f"- Lines with source `hook` ({sum(r['source'] == 'hook' for r in records)}) were written automatically by "
        "Claude Code hooks while the work happened.",
        f"- Lines with source `reconstructed` ({sum(r['source'] == 'reconstructed' for r in records)}) were written afterwards "
        "for work done before the hooks existed (the first prompts and the plan). They are marked so.",
        "- `HumanDecision` records are the person's own decisions and corrections, written from what they said in the session.",
        "- Hooks cannot see which model is running, so `model` comes from `.claude/log-defaults.json`. Edit that file if "
        "another model was used.",
        "- Checks with status `failed` are real: the mutation baseline (surviving mutants before the tests were added) and the "
        "one-character break demonstration, where a test is supposed to fail.",
        "- `mode` follows the session's permission mode: `plan` while planning, `agent` otherwise.",
        "- Older lines were created with a shorter format and converted to this one; fields they never held are `null` or empty.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    """Validate the log; unless ``--check`` was given, also write the summary. Returns the exit code."""
    records = read_log()
    found = problems(records)
    if found:
        print("\n".join(found[:20]))
        print(f"{len(found)} problem(s) in {LOG.relative_to(ROOT)}")
        return 1
    print(f"OK: {len(records)} records, all with the same {len(FIELDS)} keys, every link resolves")
    if "--check" not in sys.argv:
        SUMMARY.write_text(summary_text(records), encoding="utf-8", newline="\n")
        print(f"wrote {SUMMARY.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
